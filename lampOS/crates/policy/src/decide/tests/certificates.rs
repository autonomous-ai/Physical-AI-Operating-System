/// The bytes that `text` writes in hex.
pub fn bytes(text: &str) -> Vec<u8> {
    let digits: Vec<u8> = text
        .chars()
        .filter_map(|digit| digit.to_digit(16))
        .map(|digit| digit as u8)
        .collect();
    digits
        .chunks_exact(2)
        .map(|pair| pair[0] << 4 | pair[1])
        .collect()
}
